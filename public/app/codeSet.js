// public/app/codeSet.js — classify and filter explicit source-code sets.

export const CODE_SETS = Object.freeze(['production', 'tests', 'generated', 'vendor', 'unknown']);
const CODE_SET_LABELS = Object.freeze({
  production: 'Production',
  tests: 'Tests',
  generated: 'Generated',
  vendor: 'Vendor',
  unknown: 'Unknown',
});

const VENDOR_SEGMENTS = new Set(['vendor', 'vendors', 'third_party', 'third-party', 'node_modules']);
const GENERATED_SEGMENTS = new Set(['generated', '__generated__', 'autogenerated']);
const TEST_SEGMENTS = new Set(['test', 'tests', '__tests__', 'spec', 'specs']);
const SOURCE_ROOTS = new Set(['src', 'source', 'app', 'lib']);
const WORKSPACE_ROOTS = new Set(['apps', 'packages']);

function pathValue(value) {
  if (typeof value === 'string') return value;
  if (!value || typeof value !== 'object') return '';
  return value.path || value.file || '';
}

export function codeSetPath(value) {
  return String(pathValue(value) || '')
    .replaceAll('\0', '')
    .trim()
    .replaceAll('\\', '/')
    .replace(/^\.\//, '')
    .replace(/^\/+|\/+$/g, '')
    .replace(/\/{2,}/g, '/');
}

function testSegmentHasCodeContext(segments, index) {
  if (index === 0) return true;
  if (segments.slice(0, index).some((segment) => SOURCE_ROOTS.has(segment))) return true;
  return WORKSPACE_ROOTS.has(segments[0]) && index >= 2;
}

export function classifyCodeSet(value) {
  const path = codeSetPath(value).toLowerCase();
  if (!path) return 'unknown';
  const segments = path.split('/').filter(Boolean);
  const filename = segments.at(-1) || '';

  if (segments.some((segment) => VENDOR_SEGMENTS.has(segment))) return 'vendor';
  if (
    segments.some((segment) => GENERATED_SEGMENTS.has(segment))
    || /(?:^|[._-])(?:generated|autogenerated|gen)(?=[._-]|$)/.test(filename)
  ) return 'generated';
  if (
    segments.some((segment, index) => TEST_SEGMENTS.has(segment) && testSegmentHasCodeContext(segments, index))
    || /(?:^|[._-])(?:test|tests|spec)(?=[._-]|$)/.test(filename)
  ) return 'tests';
  if (SOURCE_ROOTS.has(segments[0])) return 'production';
  if (WORKSPACE_ROOTS.has(segments[0]) && segments.length >= 3) return 'production';
  return 'unknown';
}

export function normalizeCodeSets(values = []) {
  const selected = new Set((Array.isArray(values) ? values : [])
    .map((value) => typeof value === 'string' ? value.trim().toLowerCase() : '')
    .filter(Boolean));
  return CODE_SETS.filter((codeSet) => selected.has(codeSet));
}

export function filterGraphByCodeSets(data = {}, hiddenCodeSets = []) {
  const hidden = new Set(normalizeCodeSets(hiddenCodeSets));
  if (!hidden.size) return data;
  const sourceNodes = Array.isArray(data.nodes) ? data.nodes : [];
  const sourceEdges = Array.isArray(data.edges) ? data.edges : [];
  const nodes = sourceNodes.filter((node) => !hidden.has(classifyCodeSet(node)));
  const visibleIds = new Set(nodes.map((node) => String(node.id)));
  const edges = sourceEdges.filter((edge) => {
    const source = String(edge?.source?.id ?? edge?.source);
    const target = String(edge?.target?.id ?? edge?.target);
    return visibleIds.has(source) && visibleIds.has(target);
  });
  return { ...data, nodes, edges };
}

export function summarizeCodeSets(nodes = []) {
  const counts = new Map(CODE_SETS.map((codeSet) => [codeSet, 0]));
  for (const node of Array.isArray(nodes) ? nodes : []) {
    const codeSet = classifyCodeSet(node);
    counts.set(codeSet, counts.get(codeSet) + 1);
  }
  return CODE_SETS.map((id) => ({ id, label: CODE_SET_LABELS[id], count: counts.get(id) }));
}
